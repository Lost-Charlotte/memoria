/**
 * ⏰ **到点提醒**（2026-09-19 加）—— 待办里带 `⏰ <日期 时间>` 的条目，
 * **到点了由 F26 留意栏点名念一句**；没到点、没带标记的，一个字都不说。
 *
 * 起因（用户原话）："**现实时间 9 月 19 日下午 4 点过后提醒我让你自查**……因为咱们的上下文
 *   原文是始终没有被动过的，所以你一对比就知道到底丢没丢信息了。"
 *
 * 为什么要有它：**在待办里写一行字是靠不住的** —— 它躺在那儿，我每轮未必看得见"现在几点"。
 *   而"到点该提醒"**完全可机械判**（读待办时顺手比一下时间，成本 ≈ 0）。
 *
 * ⚠️ 反向断言（照仓库纪律 1）：**没到点、没标记、已归档的，一样都不许报** ——
 *    否则"到点提醒"会变成狼来了。
 */
import { check, done, makeArchive, sandboxHome } from './harness.mjs'

sandboxHome()

const TODO = [
  '# 待办',
  '',
  '## 四、短期 · 我能自己推 [自办]',
  '',
  '| 事项 | 原因 | 目的 |',
  '|---|---|---|',
  '| **⏰ 9/19 16:00 后自查三档裁剪** | 用户定的验收法 | 确认没丢信息 |',
  '| **⏰ 2026-09-19 20:00 写全年的** | 还没到点 | 试写全年 |',
  '| **⏰ 9/19 23:00 还没到点的事** | 未来 | 将来才做 |',
  '| **没有时间标记的普通待办** | 普通 | 普通 |',
  '',
  '## 五、已经解决并归档的 [归档]',
  '',
  '| 事情 | 结论 | 归档处 |',
  '|---|---|---|',
  '| **⏰ 9/18 10:00 已归档的过期条** | 早结了 | 某处 |',
  '',
].join('\n')

const root = makeArchive('todo-due', { 'L3-知识/工程-待办.md': TODO })
const { CFG } = await import('../lib/common.js')
CFG.archiveDir = root
const f10 = await import('../lib/f10-todo.js')
const f26 = await import('../lib/f26-backlog.js')

console.log('')

// ============================================================
// 一、解析：认三种写法，不认半吊子
// ============================================================
const AT = (y, mo, d, h, mi) => new Date(y, mo - 1, d, h, mi, 0, 0).getTime()
const NOW_REF = new Date(2026, 8, 19, 12, 0, 0) // 2026-09-19 12:00（本地）

check('解析 `⏰ 9/19 16:00`（当年 · 斜杠）', f10.parseDueAt('⏰ 9/19 16:00 后自查', NOW_REF) === AT(2026, 9, 19, 16, 0))
check('解析 `⏰ 2026-09-19 16:00`（写全年 · 横杠）', f10.parseDueAt('⏰ 2026-09-19 16:00 x', NOW_REF) === AT(2026, 9, 19, 16, 0))
check('没带 ⏰ → null', f10.parseDueAt('普通待办', NOW_REF) === null)
check('半吊子（只有日期没时间）→ **null**（不许瞎猜）', f10.parseDueAt('⏰ 9/19', NOW_REF) === null)

// ============================================================
// 二、到点筛选（现在 = 9/19 17:00）
// ============================================================
const NOW = AT(2026, 9, 19, 17, 0)
const due = f10.dueTodoItems(NOW)
check('只挑「**已经过期**」的还开着条目（1 条）', due.items.length === 1)
check('过了期的那条在里面', due.items.some((x) => String(x.item).includes('9/19 16:00')))
check('写全年那条 20:00 还没到 → **不报**', !due.items.some((x) => String(x.item).includes('写全年的')))
check('**没到点的不报**（23:00 那条）', !due.items.some((x) => String(x.item).includes('23:00')))
check('**没带 ⏰ 的不报**', !due.items.some((x) => String(x.item).includes('普通待办')))
check('归档节里的过期条**不算还开着**（不算留意）', !due.items.some((x) => String(x.item).includes('已归档的过期条')))

// ============================================================
// 三、反向：**没到点一个字都不说**
// ============================================================
const EARLY = AT(2026, 9, 19, 12, 0)
check('现在 12:00 → 16:00 那条还没到点（不报）', !f10.dueTodoItems(EARLY).items.some((x) => String(x.item).includes('9/19 16:00')))
check('现在 12:00 → 留意栏里**没有「到点了」这一行**', !f26.backlogLines(EARLY).some((l) => l.includes('到点了')))

// ============================================================
// 四、集成：到点了，留意栏里出得来
// ============================================================
const lines = f26.backlogLines(NOW)
check('到点后：留意栏里报了「到点了」', lines.some((l) => l.includes('到点了')))
check('到点后：那一行点名了具体待办', lines.some((l) => l.includes('到点了') && l.includes('9/19 16:00')))
check('文案来自文案表（不是硬编码）', f26.backlogLines(NOW).some((l) => l.includes('该主动提醒用户')))

// ============================================================
// 五、🔴 「说过就不再念」（2026-09-19 深夜加）
//    起因：这条提醒原来**没有任何"念过没"的记忆** —— 留意栏的节流按整段正文算指纹，
//    别处一变（油表读数 / 体检计数 / 待办条数）它又跟着重念，用户看到的就是
//    "**每一轮把同一件事重新推给我**"（实测一晚上 166 条注入）。
// ============================================================
// ⚠️ 用 `backlogText` 测不出来 —— 同一时刻整段正文相同，**整段指纹**本来就会把它节流掉。
//    要钉的是**它自己那条线**：别的都变（体检/油表/留底），这条也不许复活。
check('第一次 → 报出来', f26.backlogLines(NOW, 'SD2').some((l) => l.includes('到点了')))
check('🔴 同一会话再来一次 → 这条不再出现（别的留意照常）', !f26.backlogLines(NOW, 'SD2').some((l) => l.includes('到点了')))
check('换一个会话 → 照样说（宁可多说，不可漏说）', f26.backlogLines(NOW, 'SD3').some((l) => l.includes('到点了')))
f26.resetBacklogThrottle('SD2')
check('压缩后清空节流 → 重念一遍（上下文真被甩掉了）', f26.backlogLines(NOW, 'SD2').some((l) => l.includes('到点了')))

done()
