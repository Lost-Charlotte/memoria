// ============================================================
// 引用去路径 —— 匹配规则的回归测试（2026-09-28 · 工程「引用与索引」节点 4「工具收口」）
// ============================================================
// 为什么要这个文件：规则原来写在 `tools/引用去路径.mjs` 肚子里 ⇒ **测不到**。
// 抽到 `lib/refs-to-name.js` 之后，这里 import 的是**与 CLI 同一份**规则 —— 也就钉住了"它认得出什么"。
//
// 🔴 每条断言背后都是一次真踩过的坑（教训写在 `lib/refs-to-name.js` 头部）：
//   · 多层子目录**必须**咬得上（L3 已分 9 个子目录，咬不上＝漏检）
//   · 层名段不许含 `.`（否则 `L2-数据\01-事件表…` 会被咬成 `-事件表…`，真文件被误报"重名"）
//   · 不许咬裸路径 / 绝对路径（`~\.dsh\plugins\…\改档.mjs` 那次造了 100+ 处假命中）
//   · 咬住的必须是**整条路径**，不是后半截（`…\工具-认盘取盘符.ps1` 被咬成 `具-认盘取盘符.ps1`）
// ============================================================
import { REF_RE, findRefs, looksHistorical } from '../lib/refs-to-name.js'

let pass = 0
let fail = 0
const check = (name, ok) => {
  if (ok) {
    pass += 1
    console.log(`  ✅ ${name}`)
  } else {
    fail += 1
    console.log(`  ❌ ${name}`)
  }
}

const one = (line) => findRefs(line)[0] ?? null

// ---- 单层（原有的能力，别退化） ----
check('单层：`L1-必读\\00-总览-我们干过什么.md` 咬得上', one('见 L1-必读\\00-总览-我们干过什么.md 那行')?.name === '00-总览-我们干过什么.md')
check('单层：正斜杠也认', one('见 L3-知识/参考-条线归属口径.md')?.name === '参考-条线归属口径.md')
check('单层：带行号时，行号不进食（`:113` 留在外面）', one('见 L1-必读\\工具速查.md:113 那段')?.text === 'L1-必读\\工具速查.md')

// ---- 🔴 多层（2026-09-28 新增的能力）----
check(
  '多层：`L3-知识\\参考\\指南-装插件的方法.md` 咬得上（且 name 只取文件名）',
  one('见 L3-知识\\参考\\指南-装插件的方法.md 那份')?.name === '指南-装插件的方法.md',
)
check(
  '多层：三层子目录也认',
  one('见 L4-施工\\统一度量衡\\层与命名-讨论稿.md 里说的')?.name === '层与命名-讨论稿.md',
)
check(
  '多层：证据层那种"层\\子目录\\…\\文件.ps1"要咬**整条**（不是后半截）',
  one('跑 L5-证据\\公盘F整理-2026-09-13\\脚本\\工具-认盘取盘符.ps1 那个')?.text === 'L5-证据\\公盘F整理-2026-09-13\\脚本\\工具-认盘取盘符.ps1',
)
check(
  '多层：咬住的整条以扩展名收口，后面的话不进来',
  one('见 L3-知识\\参考\\指南-装插件的方法.md，后面还有字')?.text === 'L3-知识\\参考\\指南-装插件的方法.md',
)

// ---- 层名段不许含 `.`（那次"真文件被报成重名"的坑） ----
check(
  '层名段不许含 `.`：`L2-数据\\01-事件表-我们做过什么.md` 咬出**完整文件名**',
  one('见 L2-数据\\01-事件表-我们做过什么.md 的目录')?.name === '01-事件表-我们做过什么.md',
)
check(
  '文件名里有括号 / 中点也照样咬全',
  one('见 L1-必读\\地图-档案结构（机器生成）.md 一眼')?.name === '地图-档案结构（机器生成）.md',
)

// ---- 不许咬的（假命中） ----
check('裸文件名**不算**（试跑第一版就是栽在这）', findRefs('改档.mjs 这个工具').length === 0)
check('绝对路径 / 插件包里的入口**不算**', findRefs('node ~\\.dsh\\plugins\\dsh-memoria\\tools\\改档.mjs --txn x.json').length === 0)
check('已经去过路径的（光文件名）**咬不上** —— 幂等的根据', findRefs('见 指南-装插件的方法.md 那份').length === 0)
check('没有层名前缀的普通路径不算', findRefs('见 参考\\指南-装插件的方法.md 那份').length === 0)

// ---- 一行多处 ----
{
  const hits = findRefs('先看 L1-必读\\工具速查.md，再看 L3-知识\\参考\\指南-装插件的方法.md')
  check('一行里多处引用都收得到（1 处单层 ＋ 1 处多层）', hits.length === 2 && hits[0].name === '工具速查.md' && hits[1].name === '指南-装插件的方法.md')
}

// ---- 历史叙述判据（拒的那一类） ----
check('历史叙述：时间轴那种"等级行"认得出', looksHistorical('| ❗ | **T133** | 2026-09-14 23:10 | 丢了 4 个文件 |'))
check('历史叙述：`⭐` / `○` 也认', looksHistorical('| ⭐ | **T307** | 2026-09-26 14:00 | 某事 |') && looksHistorical('| ○ | **T308** | 2026-09-26 14:01 | 某事 |'))
check('**不是**历史叙述：事件表正文里的"指引"（那是活指针，照改）', !looksHistorical('> **指引**：L3-知识\\参考\\指南-装插件的方法.md'))
check('**不是**历史叙述：普通正文', !looksHistorical('见 L1-必读\\工具速查.md 那一行'))

// ---- 正则本身：`g` 标志（调用方各自 matchAll） ----
check('REF_RE 带 `g`（否则 matchAll 会抛）', REF_RE.global === true)

console.log(`\n结果：${pass} 通过 / ${fail} 失败`)
process.exit(fail === 0 ? 0 : 1)
