/** 装配时的自查：代号不许重复、每项必须能被装（有 register / tool / selfCheck / mergedInto）、**每个代号都得恰好分到一间室**。 */
export function manifestProblems() {
  const out = []
  const seen = new Set()
  for (const c of CAPS) {
    if (!c.id || !c.title) out.push(`有条目缺 id/title：${JSON.stringify(c)}`)
    if (seen.has(c.id)) out.push(`代号重复：${c.id}`)
    seen.add(c.id)
    // `mergedInto` 也算"装得上"：它的**工具面**并进了另一个工具，能力内核照旧在跑（2026-09-18 工具合并）。
    if (!c.register && !c.toolName && !c.selfCheck && !c.mergedInto) {
      out.push(`${c.id} 既没有 register、也没有 tool、也没有 selfCheck（也没有 mergedInto）—— 装了等于没装`)
    }
    if (c.mergedInto && !CAPS.some((x) => x.id === c.mergedInto)) {
      out.push(`${c.id} 写着 mergedInto:${c.mergedInto}，但清单里没有这个代号（并到哪儿去了？）`)
    }
  }
  // 分室（面板"按功能分室"那张表）：漏分 / 分重 / 指向不存在的代号，都是机械可判的
  const homed = new Map()
  for (const [room, ids] of ROOMS) {
    for (const id of ids) {
      if (!seen.has(id)) out.push(`分室「${room}」里有个不存在的代号：${id}`)
      if (homed.has(id)) out.push(`${id} 被分到了两间室：「${homed.get(id)}」和「${room}」`)
      homed.set(id, room)
    }
  }
  for (const id of seen) if (!homed.has(id)) out.push(`${id} 没分到任何一间室（面板的"分室"视图里会看不见它）`)
  return out
}
