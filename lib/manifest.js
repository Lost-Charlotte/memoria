// 后续每次添加都会麻烦**"（并让我参考 `Phant0Meow/dsh-meow-memory` 的结构：一个能力一个模块）。
//
// 所以这里的规矩只有一条：**加功能＝加一个文件 ＋ 在这张表加一行。**
//   · 能力内核（`lib/<代号>-<名字>.js`）只 import `common.js`，自己不碰 `ctx` 的装配细节；
//   · 这张表说清"装谁、叫什么、干什么、启动时报什么"；
//   · `index.js` 只负责**照着表装**（它不再逐条写 try/catch）。
//
// 每项字段：
//   id        能力代号（F1/F2/F5…）—— **不许重复**（撞号＝两件事共用一个名字，测试会拦）
//   title     中文名（给人看，也供将来的控制台面板读）
//   what      一句话：它替我做掉什么（给人看）
//   kind      归类：'hook'（挂事件）· 'tool'（给我用的工具）· 'guard'（拦截）· 'sensor'（自检报告）
//   register  kind='hook'/'guard' 时：`(ctx) => void`
//   tool      kind='tool' 时：ToolDefinition
//   selfCheck 可选：启动时自报工作量的函数（"沉默 ≠ 正常"）
//   mergedInto 可选（**2026-09-18 加**）：这个能力的**工具面**已并进另一个工具 ——
//              它的**能力内核照旧在跑**（判定、自检、注入一个字没变），只是不再单独注册一个工具。
//              写在这里是为了"能力清单仍然是完整的"（面板上看得见、历史编号不消失），
//              同时让 `manifestProblems()` 不再要求它必须自带 tool/register/selfCheck。
//
// ⚠️ 这里**只写"装什么"**；判定逻辑一律在各模块里。别把逻辑搬进来 —— 那会把它变成第二个上帝文件。

