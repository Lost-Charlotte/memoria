/**
 * F38 · **安全总监**（2026-10-21 建）
 *
 * ============================================================
 * 它存在的理由（用户当天定的架构原则，原话）
 * ============================================================
 *
 * > 「**能机器判的不给 AI 看**」……「**我们需要一个安全总监，他每轮检测所有口子，跟我说正常，
 * >    就代表全正常。其中一个不正常，就像你说的，1 个不正常。然后说点他的命。具体的你会去查的**」
 *
 * 加上后半夜定下的**说话规则**：
 *
 * > 「**安全总监在一开始报一次正常。然后就不用出声了。除非他发现什么地方不正常。
 * >    就是，开局报一声，证明它存在。然后他就可以不出声了。除非有问题。有问题他再出声。
 * >    你修好了。他报全正常。然后又不出声了。直到下次出问题。**」
 *
 * ============================================================
 * 三问（《施工手册》「动手之前先过三问」）
 * ============================================================
 *
 * ① **能不能并进已有能力？**
 *    ⇒ **不能**。它不是某个口子的分支，是**汇总层**：读 `health/` 下所有人写的那一行，判"全绿吗"。
 *      并进任何一个口子都会立刻变回"那个口子自己的看法"，汇总就没了。
 *
 * ② **它要不要每轮说话？**
 *    ⇒ **不**。它只报**变化**（首轮 / 由绿转红 / 由红转绿），状态没变一个字不说。
 *      这正是它省的地方 —— 从前是每个口子每轮各说一句，现在是**一条链只报一次状态切换**。
 *
 * ③ **它会不会静默失效？**
 *    ⇒ 会，所以它有**两条自证**：
 *      · **每步都写 `health/F38.json`**（心跳 —— 考勤（F34）将来靠这个判它死活，与它判别人同一把尺子）；
 *      · **状态切换时写 `memoria.log`**（"总监：全部正常" / "总监：2 处不正常"）。
 *      所以"它一声不吭"有两种可区分的解释：日志里心跳还在（＝真没问题） vs 心跳停了（＝它死了）。
 *
 * ============================================================
 * 边界（写死，别越）
 * ============================================================
 *
 * · 它**只汇总、不诊断** —— 红的时候说"是哪几处"，不展开为什么；**细节我自己去查**（`dangan_status` / 日志）。
 * · 它**不拦人**（不是闸门），也**不改档案**（只写 `~/.dsh` 下的状态与日志）。
 * · 它**只读 `health/`** —— 不自己去扫档案，那样就退化成"又一个全档扫描"了。
 */

import { CAP_STATS, HEALTH_IDS, capTick, log, readHealth, writeHealth } from './common.js'

/**
 * 上一次判定的**签名**（`null` ＝ 本进程还没判过）。**只在内存**：重启后首轮会重新报一次，这是对的。
 *
 * ⚠️ **为什么不是 `lastOk`（一个 bool）**：2026-10-21 的测试当场抓出来 ——
 *    红从「1 处」变成「2 处」时 bool 还是 `false`，于是它**不说话**。
 *    而用户的话是「**有问题他再出声**」：**情况变了就该说**。
 *    ⇒ 签名记 `ok:<项数>` / `bad:<哪些 id 排序后>`，红的**数量或对象**一变就算"变了"。
 */
let lastSig = null

/** 红的时候最多列几处（再多就不念了 —— 细节我去查，念多了又是刷屏）。 */
const MAX_LIST = 4

/**
 * **心跳**（每步调）：只把 `at` / `step` 往前挪，**不判、不说话**。
 *
 * 🔴 为什么必须跟 `directorLine()` 拆开（2026-10-22 实测两次误报）：
 *    `directorLine()` 只挂在"**真有用户消息**"的那一步（F1 的注入分支），而 `watchTick` 是**每一步**都跑
 *    ⇒ **步数在涨、心跳不涨** ⇒ 考勤判"总监掉队 4 步"（我查个东西走 4 步就喊一次）。
 *    第一次修把"按钟判"换成"按步数判"，治了"睡一晚被当死"，**没治"没说话的那几步"**。
 *    ⇒ 现在：**心跳跟步数走**（每步写）· **判断跟注入走**（有话说才判）。
 * ⚠️ 心跳**不改 `ok` / `brief`** —— 那红绿状态是上次真判出来的，不许被心跳冲掉。
 */
export function directorBeat() {
  try {
    const old = readHealth().find((h) => h && h.id === 'F38') || {}
    const stepNow = Number(CAP_STATS.get('F34')?.count) || 0
    writeHealth('F38', old.ok !== false, old.brief || '还没判过', { step: stepNow })
  } catch {
    /* 心跳失败不许影响主流程 */
  }
}

/**
 * 判一遍全场，并按"报变化"的规则决定说不说。
 *
 * @returns {string} 该说的话（一句）；**沉默时返回空串**。
 *   ⚠️ 不管说不说，**每次调用都会写一次 `health/F38.json`** —— 那是它的心跳，不是给人看的话。
 */
export function directorLine() {
  let all = []
  try {
    all = readHealth()
  } catch {
    /* 读不到就当"一个口子都没报"—— 下面按"全绿但空"处理 */
  }

  // ⚠️ 把**自己**那份排除掉：F38 也写在 health/ 里，不排除就会拿上次的自己判这次（永远绿）。
  // 🔴 2026-10-22：**只认名单里的 id**（`HEALTH_IDS`）—— 撤掉的口子会留下旧文件，
  //    不筛的话它照样被算进"N 项"（门卫 F30 撤掉当天就撞上：文件还在，总监还以为它在报）。
  const others = all.filter((h) => h && h.id && h.id !== 'F38' && HEALTH_IDS.includes(h.id))
  const bad = others.filter((h) => h.ok !== true)
  const ok = bad.length === 0

  // ---- 心跳：每步都写（考勤靠它判我死活）----
  // 🔴 2026-10-22 加 `step`：把**此刻的步数**一起记下 —— 考勤拿"我走了几步、它没跟上"判死活，
  //    而不是拿墙上的钟判（拿钟判会把"昨晚没人用"误报成"它死了"，580 分钟那次就是这么来的）。
  const stepNow = Number(CAP_STATS.get('F34')?.count) || 0
  writeHealth('F38', ok, ok ? `${others.length} 项全绿` : `${bad.length} 处不正常`, { step: stepNow })
  // 🔴 **2026-10-22 补**：它原来**不在"干活统计"里**（用户截图证实：`dangan_status` 的能力那一行没有 F38）。
  //    原因是它一次 `capTick` 都没调 —— 自报了"健康状态"，却**没自报"我这一程干过活"**。
  //    "沉默 ≠ 正常"是双向的：它对自己也要成立，否则它哪天悄悄不跑了，谁都不会察觉。
  try {
    capTick('F38', `判了 ${others.length} 项`)
  } catch {
    /* 计数失败不影响判 */
  }

  // ---- 说话规则：只报变化（"变"看签名：全绿项数 / 红的是哪几处）----
  const sig = ok ? `ok:${others.length}` : `bad:${bad.map((h) => String(h.id)).sort().join(',')}`
  const changed = lastSig === null || lastSig !== sig
  lastSig = sig
  if (!changed) return ''

  if (ok) {
    // 一个口子都没报过时，别硬说"全部正常"（那等于替不存在的东西担保）
    if (others.length === 0) return ''
    log(`总监：全部正常（${others.length} 项）`)
    return `🛡 **安全总监**：全部正常（${others.length} 项）`
  }

  const shown = bad.slice(0, MAX_LIST)
  const marks = ['①', '②', '③', '④']
  const list = shown.map((h, i) => `${marks[i] ?? '·'} ${h.brief || h.id}`).join(' · ')
  const more = bad.length > shown.length ? ` …还有 ${bad.length - shown.length} 处` : ''
  log(`总监：${bad.length} 处不正常 —— ${bad.map((h) => `${h.id}:${h.brief}`).join(' / ')}`)
  return `🛡 **安全总监**：⚠️ **${bad.length} 处不正常** —— ${list}${more}`
}

/** 测试用：忘掉"上次判过什么"（重启时天然如此，测试里要能手动重来）。 */
export function __resetDirector() {
  lastSig = null
}

/** 自报工作量（清单里每个能力都要有 —— `manifestProblems()` 会查"装了等于没装"）。 */
export function reportF38() {
  const all = readHealth().filter((h) => h && h.id !== 'F38')
  const bad = all.filter((h) => h.ok !== true)
  const last = lastSig === null ? '还没判过' : lastSig.startsWith('ok:') ? '上次：全绿' : '上次：有红'
  return `安全总监：读到 ${all.length} 项健康状态，${bad.length} 处红 · ${last}`
}

/** 注册入口（**本步只做"能装上去"**：真正的每步调用挂在 F1 的 pre-step 里）。 */
export function registerF38(ctx) {
  try {
    log('安全总监（F38）已就位：只报状态变化，全绿时一个字不说', { silent: true })
  } catch {
    /* 日志失败不许影响装配 */
  }
  // ⚠️ 这里**故意不挂 `agent/pre-step`** —— 钩子只许 F1 挂一处（脚手架的 on() 是"后注册顶掉先注册"，
  //    多挂一处会把 F1 那条链整条顶掉；F23 踩过两次）。F1 会调 `directorLine()`。
  void ctx
}
