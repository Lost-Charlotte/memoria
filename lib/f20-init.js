/** 拼绝对路径，**不许跑出档案根**（防"配置写错就把文件建到别处"）。 */
function within(root, rel) {
  const abs = resolve(root, rel)
  const base = resolve(root)
  if (abs !== base && !abs.startsWith(base + sep)) throw new Error(`路径跑出档案根了：${rel}`)
  return abs
}

/**
 * 建档案（**默认干跑**）。
 *
 * @param {{apply?:boolean, dir?:string, now?:{ymd:string}}} opt
 * @returns {{ok:boolean, applied:boolean, dir:string, created:string[], skipped:string[], dirs:string[], errors:string[], note:string}}
 */
export function bootstrap(opt = {}) {
  const dir = opt.dir ?? CFG.archiveDir
  const apply = opt.apply === true
  const now = opt.now ?? defaultNow()
  const created = []
  const skipped = []
  const madeDirs = []
  const errors = []

  // 目录：缺的才建（已存在的一个都不动）
  for (const d of DIRS) {
    try {
      const abs = within(dir, d)
      if (existsSync(abs)) continue
      madeDirs.push(d)
      if (apply) mkdirSync(abs, { recursive: true })
    } catch (e) {
      errors.push(`目录 ${d}：${e && e.message ? e.message : e}`)
    }
  }

  // 文件：**只补缺，绝不覆盖**
  for (const f of skeletonFiles(now)) {
    try {
      const abs = within(dir, f.rel)
      if (existsSync(abs)) {
        skipped.push(f.rel)
        continue
      }
      // 父目录也得在（L3 下可能有子目录）
      const parent = dirname(abs)
      if (!existsSync(parent) && apply) mkdirSync(parent, { recursive: true })
      created.push(f.rel)
      if (apply) writeFileSync(abs, f.text, 'utf8')
    } catch (e) {
      errors.push(`文件 ${f.rel}：${e && e.message ? e.message : e}`)
    }
  }

  const r = {
    ok: errors.length === 0,
    applied: apply,
    dir,
    created,
    skipped,
    dirs: madeDirs,
    errors,
    note: apply ? '已按骨架建出（原有内容一个字都没动）' : '干跑：一个字都没写',
  }
  if (apply) {
    try {
      capTick('F20', `建 ${created.length} 份 / 补 ${madeDirs.length} 目录`)
      log(`F20 初始化：在 ${dir} 建出 ${created.length} 份文件、${madeDirs.length} 个目录（跳过已存在的 ${skipped.length} 份）`, { silent: true })
    } catch {
      /* 计数/日志失败不阻塞 */
    }
  }
  return r
}

/** 把 bootstrap 的结果写成给模型看的文本。 */
export function formatBootstrap(r) {
  const L = []
  L.push(`【dangan_init】${r.applied ? '✅ 已建' : '🔎 干跑（一个字都没写）'} —— 档案根：\`${r.dir}\``)
  L.push('')
  if (r.dirs.length > 0) L.push(`· 目录：${r.dirs.join('、')}`)
  if (r.created.length > 0) L.push(`· 要建的文件（${r.created.length}）：${r.created.join('、')}`)
  else L.push('· 要建的文件：**没有**（该有的都已在）')
  if (r.skipped.length > 0) L.push(`· **已存在、跳过（一个字都没动）**：${r.skipped.join('、')}`)
  if (r.errors.length > 0) {
    L.push('')
    L.push('⚠️ 有错：')
    for (const e of r.errors) L.push(`   · ${e}`)
  }
  L.push('')
  if (!r.applied) {
    L.push('这是干跑。**确认清单没问题**，再调一次 `dangan_init apply:true` 真建。')
  } else {
    L.push('建好了。接下来**照 W4 收尾**：把"档案初始化"这件事落进 **L3**（用 `dangan_weave pattern:\'落档\'`，带 `commit:true`）。')
    L.push('⚠️ 骨架里 `T1` / `E1` 是**示例行**，贴完格式后要删掉。')
  }
  return L.join('\n')
}

