/** 档案根是否在（一个目录都算"在"）。 */
export function rootExists(dir = CFG.archiveDir) {
  try {
    return existsSync(dir) && statSync(dir).isDirectory()
  } catch {
    return false
  }
}

/**
 * 一眼看清档案状态：
 *   · \`missing\` —— 根目录都不在（全新环境最常见的形态）
 *   · \`empty\`   —— 根在、但**入口与关键件一份都没有**（空壳 / 只建了目录）
 *   · \`partial\` —— 入口在，但**关键附属件缺**（铁律 / 使用说明 少哪份列哪份）
 *   · \`ok\`      —— 关键件齐
 */
export function archiveState(dir = CFG.archiveDir) {
  const has = (rel) => {
    try {
      return existsSync(join(dir, rel))
    } catch {
      return false
    }
  }
  if (!rootExists(dir)) return { kind: 'missing', dir, missing: ['（整个档案根目录）'], exists: [] }

  const keys = [
    [F.entry, '入口文件'],
    [join('L1-必读', F.rules), '铁律'],
    [join('L1-必读', F.howto), '使用说明'],
  ]
  const present = keys.filter(([rel]) => has(rel)).map(([, name]) => name)
  const missing = keys.filter(([rel]) => !has(rel)).map(([, name]) => name)

  if (present.length === 0) return { kind: 'empty', dir, missing, exists: present }
  if (missing.length === 0) return { kind: 'ok', dir, missing, exists: present }
  return { kind: 'partial', dir, missing, exists: present }
}

