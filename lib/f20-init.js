/**
 * 启动自检。
 * ⚠️ **这条的存在理由**：插件"坏掉是静默的" —— 档案不在时，入口读不到、铁律找不到、
 *    工具全返回空，**却没有任何一行告诉接手的人为什么**。这一条把"为什么 + 怎么办"说白。
 */
export function startupAdvice() {
  let st
  try {
    st = archiveState()
  } catch (e) {
    log(`F20 初始化自检失败（fail-open）：${e}`)
    return
  }
  if (st.kind === 'missing') {
    log(
      `F20 初始化：**档案根不存在**（${st.dir}）—— 这座档案还没建。` +
        `要建就调工具 \`dangan_init\`（默认干跑，确认后 apply:true）；` +
        `要指向已有的档案，就去 cordis 配置里改 archiveDir（或设环境变量 GAI_DANG_ROOT）。`,
      { silent: false }
    )
    return
  }
  if (st.kind === 'empty') {
    log(`F20 初始化：档案根在（${st.dir}）但关键件一份都没有 —— 调 \`dangan_init\` 可以按骨架补出来（只补缺、不覆盖）`)
    return
  }
  if (st.kind === 'partial') {
    log(`F20 初始化：档案缺 ${st.missing.join('、')} —— 调 \`dangan_init\` 可以补齐（只补缺、不覆盖）`)
    return
  }
  log(`F20 初始化：档案关键件齐全（入口 / 铁律 / 使用说明）`, { silent: true })
}
