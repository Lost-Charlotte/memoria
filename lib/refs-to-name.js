/**
 * 认"带层的引用"的**唯一那条正则**（`g` 标志：调用方各自 `matchAll`）。
 *
 * · **层名段**（`L\d+-` 之后那一段）**不许含 `.`**；
 * · 尾巴是"**一或多次** `分隔符 + 段`" ⇒ **层数不限**；
 * · 段里允许含 `.`（如 `参考-名词解释（说人话版）.md`），靠结尾的 `\.(扩展名)\b` 收口。
 * · ✅ **括号要吃得下**（2026-09-28 放开）：旧字符类把 `（）` 与 `()` 也排掉了，于是
 *   **档案里那一大批带括号的文件名一直咬不上**（`地图-档案结构（机器生成）.md` ·
 *   `参考-老馆与新馆（现状总纲）.md` · `事件类型的md写法（规则）.md` …）—— 这是**第二个盲区**，
 *   和"多层子目录"是同一类病（该改的既不报改、也不报拒）。
 *   放开是安全的：匹配**必须以 `\.(扩展名)\b` 收口** ⇒ `` `L3-知识\x.md`（总目录） `` 这种
 *   只会咬到 `x.md`（贪婪回溯到最后一个合法结尾）；万一把不该连的连起来，名字也不在
 *   文件名集合里 ⇒ 落进"**不在名字集合里**"那条**拒**，不会误改。
 */
export const REF_RE =
  /L\d+-[^.\s`|。，；、:：'"“”\\/]+(?:[\\/][^\s`|。，；、:：'"“”\\/]+)+\.(?:md|txt|ps1|mjs|cmd|bat|csv|json|png|jpe?g|webp|gif|html?)\b/gi

/**
 * 一行里把"带层的引用"全挖出来。
 *
 * @param {string} line
 * @returns {Array<{start:number,end:number,text:string,name:string,kind:'path'}>}
 *   `start..end` 是**要换成"光文件名"的那一段**；`name` 是**文件名**（最后一个分隔符之后）。
 */
export function findRefs(line) {
  const out = []
  const push = (raw, idx, name) => {
    out.push({ start: idx, end: idx + raw.length, text: raw, name, kind: 'path' })
  }
  // ⚠️ **层名段必须单独一段**（`L\d+-` 后面不许再出现分隔符、也不许出现 `.`）—— 试跑几版才定：
  //    原来把层名写成 `L\d+-[^\s…]*?`，字符类里**没排掉分隔符** ⇒
  //      `L1-必读\地图-档案结构（机器生成）.md` 被咬成 **`L1-必读\地图`**（假命中）；
  //    第二版排掉了分隔符、**没排掉 `.`** ⇒ 反向又错：
  //      `L3-知识/参考-名词解释（说人话版）.md` 咬成 **`L3-知识/参考`**，
  //      而 `L2-数据\01-事件表-我们做过什么.md` 更毒 —— 层名段把 `\01` 吃进去后
  //      文件名段变成 **`-事件表-我们做过什么.md`**，于是**真文件被报成"重名"**（拒得莫名其妙）。
  //    ⇒ 三段都齐才算：**层名段 ＋（分隔符 ＋ 段）一或多次 ＋ `.扩展名`**，且层名段不许含 `.`。
  for (const m of line.matchAll(REF_RE)) {
    const raw = m[0]
    push(raw, m.index, raw.slice(Math.max(raw.lastIndexOf('\\'), raw.lastIndexOf('/')) + 1))
  }
  return out
}

/**
 * 这一行是不是**历史叙述**（＝"当时这件事指引去哪"的记录，不是指针）。
 *
 * 判据（机械可判、可复核）：**表格行 ＋ 第一格是等级符号**。
 * 时间轴每一行都是 `| 等级 | **T<号>** | 时间 | 发生了什么 |`（等级只看 `❗ ⭐ ○`）；
 * 事件表正文里那些 `> **指引**：…` 不带表格竖线 ⇒ 自然不算，**照改**（它们是活指针）。
 */
export function looksHistorical(line) {
  const m = line.match(/^\s*\|\s*([^|]*?)\s*\|/) // 取第一格
  if (!m) return false
  const first = m[1].trim()
  return /^(?:[❗⭐○⚠️]|\*\*[❗⭐○⚠️]\*\*)$/.test(first)
}
